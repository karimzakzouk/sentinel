"""Postmortem generator — turns an incident into a written retrospective.

Uses the frontier LLM to produce a markdown postmortem that summarizes:
  - What happened
  - Why (the root cause)
  - How we found it (the investigation trace)
  - The fix that was applied
  - Action items for preventing recurrence
"""
from __future__ import annotations

import json
import logging
from typing import Any

from openai import AsyncOpenAI
from tenacity import retry, stop_after_attempt, wait_exponential

from sentinel_common import Incident

log = logging.getLogger(__name__)


SYSTEM_PROMPT = """You are Sentinel's Postmortem Generator. Given a resolved
incident's full state, write a markdown postmortem following the standard SRE
template:

  # Postmortem: <incident_id>
  ## Summary
  ## Impact
  ## Root Cause
  ## Timeline
  ## What Went Well
  ## What Went Wrong
  ## Action Items

Be concise and factual. Don't speculate. If a section isn't applicable,
omit it. Use the agent_trace and evidence arrays to build the Timeline."""


class PostmortemGenerator:
    def __init__(self, settings: Any):
        self.settings = settings
        self.client = AsyncOpenAI(
            base_url=settings.llm_base_url,
            api_key=settings.llm_api_key or "missing",
        )

    @retry(stop=stop_after_attempt(2), wait=wait_exponential(min=1, max=5))
    async def generate(self, incident: Incident) -> str:
        """Generate a markdown postmortem for the incident."""
        user_msg = self._build_prompt(incident)
        try:
            r = await self.client.chat.completions.create(
                model=self.settings.llm_frontier_model,
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_msg},
                ],
                temperature=0.3,
                max_tokens=3000,
            )
            return r.choices[0].message.content or ""
        except Exception as e:  # noqa: BLE001
            log.warning("Postmortem generation failed: %s", e)
            return self._fallback_postmortem(incident)

    def _build_prompt(self, incident: Incident) -> str:
        rc = incident.state.root_cause
        fp = incident.state.fix_proposal
        er = incident.state.execution_result
        parts = [
            f"# Incident ID: {incident.incident_id}",
            f"Service: {incident.cluster.service} (namespace: {incident.cluster.namespace})",
            f"Severity: {incident.cluster.severity}",
            f"Created at: {incident.created_at.isoformat()}",
            f"Status: {incident.status.value}",
            "",
            "## Cluster Summary",
            incident.cluster.summary,
            "",
            "## Root Cause",
            f"Statement: {rc.statement if rc else 'unknown'}",
            f"Category: {rc.category if rc else 'unknown'}",
            f"Confidence: {rc.confidence if rc else 0:.3f}",
            f"Source files: {rc.source_files if rc else []}",
            "",
            "## Fix Applied",
            f"Type: {fp.fix_type.value if fp else 'unknown'}",
            f"Description: {fp.description if fp else 'unknown'}",
            f"PR URL: {er.pr_url if er else 'n/a'}",
            f"K8s response: {json.dumps(er.k8s_response)[:500] if er and er.k8s_response else 'n/a'}",
            "",
            "## Agent Trace",
        ]
        for entry in incident.state.agent_trace:
            parts.append(f"- {json.dumps(entry)}")
        parts.extend([
            "",
            "## Evidence",
        ])
        for e in incident.state.evidence[:10]:
            parts.append(f"- **{e.e_id}** ({e.source}): {json.dumps(e.result)[:300]}")
        parts.extend([
            "",
            "## Beta Distribution After Resolution",
            f"alpha={incident.beta_alpha}, beta={incident.beta_beta}",
            f"posterior mean = {incident.beta_alpha / (incident.beta_alpha + incident.beta_beta):.3f}",
            "",
            "## Your Task",
            "Write the markdown postmortem now.",
        ])
        return "\n".join(parts)

    def _fallback_postmortem(self, incident: Incident) -> str:
        rc = incident.state.root_cause
        fp = incident.state.fix_proposal
        return f"""# Postmortem: {incident.incident_id}

## Summary
Autonomous Sentinel investigation resolved an incident on `{incident.cluster.service}`.

## Impact
{incident.cluster.summary}

## Root Cause
{rc.statement if rc else 'unknown'}

## Fix Applied
Type: `{fp.fix_type.value if fp else 'unknown'}`
Description: {fp.description if fp else 'n/a'}

## Action Items
- Review the agent trace for accuracy
- Validate the fix is still in effect after 24 hours

---
_Generated by Sentinel (LLM was unavailable; this is a fallback template.)_
"""
